#!/usr/bin/env bash
# Install (or re-run to repair) the VPSPilot control plane on Ubuntu/Debian.
#
#   curl -fsSL https://raw.githubusercontent.com/<you>/<api-repo>/main/deploy/install.sh \
#     | sudo bash -s -- --domain pilot.example.com --email you@example.com
#
# Options:
#   --domain HOST        public hostname for the dashboard (required)
#   --email ADDRESS      for Let's Encrypt notices (recommended)
#   --api-repo URL       git URL of the API repository
#   --web-repo URL       git URL of the dashboard repository
#   --branch NAME        branch to install (default: main)
#   --resend-key KEY     Resend API key for email (sign-in codes are logged until set)
#   --internal-tls       use Caddy's internal CA instead of Let's Encrypt (testing)
#
# Re-running keeps the existing secrets and data.
set -euo pipefail

DOMAIN=""
EMAIL=""
API_REPO="${VPSPILOT_API_REPO:-https://github.com/philtechphilips/VPS-PIlot-BE.git}"
WEB_REPO="${VPSPILOT_WEB_REPO:-https://github.com/philtechphilips/Vps-Pilot.git}"
BRANCH="main"
RESEND_KEY=""
TLS="auto"
ROOT="/opt/vpspilot"
PROXY_DIR="/var/lib/vpspilot-proxy"

while [ $# -gt 0 ]; do
  case "$1" in
    --domain) DOMAIN="$2"; shift 2 ;;
    --email) EMAIL="$2"; shift 2 ;;
    --api-repo) API_REPO="$2"; shift 2 ;;
    --web-repo) WEB_REPO="$2"; shift 2 ;;
    --branch) BRANCH="$2"; shift 2 ;;
    --resend-key) RESEND_KEY="$2"; shift 2 ;;
    --internal-tls) TLS="internal"; shift ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "Unknown option: $1" >&2; exit 2 ;;
  esac
done

say() { printf '\033[1;35m==>\033[0m %s\n' "$*"; }
die() { printf '\033[1;31mError:\033[0m %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "Run as root (sudo)."
[ -n "$DOMAIN" ] || die "Pass --domain pilot.example.com"
echo "$DOMAIN" | grep -Eq '^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z0-9-]{2,63}$' || die "That doesn't look like a hostname: $DOMAIN"
. /etc/os-release
case "$ID" in ubuntu|debian) ;; *) die "Unsupported OS: $PRETTY_NAME. VPSPilot supports Ubuntu and Debian." ;; esac

say "Installing VPSPilot on $PRETTY_NAME for https://$DOMAIN"
export DEBIAN_FRONTEND=noninteractive NEEDRESTART_MODE=a
apt-get update -qq
apt-get install -y -qq git curl ca-certificates openssl >/dev/null

if ! docker compose version >/dev/null 2>&1; then
  say "Installing Docker"
  curl -fsSL https://get.docker.com | sh >/dev/null
fi
systemctl enable --now docker >/dev/null 2>&1 || true

# Ports 80/443 must be free (or already ours).
for port in 80 443; do
  holder=$(ss -ltnpH "sport = :$port" 2>/dev/null | head -1 || true)
  if [ -n "$holder" ] && ! docker ps --format '{{.Names}}' | grep -qx vpspilot-proxy; then
    die "Port $port is in use: $holder
Stop that service (or move its sites behind VPSPilot later) and run this again."
  fi
done

say "Fetching the code ($BRANCH)"
mkdir -p "$ROOT"
for pair in "api|$API_REPO" "web|$WEB_REPO"; do
  name="${pair%%|*}"; url="${pair#*|}"
  if [ -d "$ROOT/$name/.git" ]; then
    git -C "$ROOT/$name" fetch -q origin "$BRANCH" && git -C "$ROOT/$name" checkout -q -B "$BRANCH" "origin/$BRANCH"
  else
    git clone -q --branch "$BRANCH" "$url" "$ROOT/$name"
  fi
done

ENV_FILE="$ROOT/api/deploy/.env"
if [ ! -f "$ENV_FILE" ]; then
  say "Generating secrets"
  umask 077
  cat > "$ENV_FILE" <<ENV
# Generated by install.sh. Back this file up: it holds the keys that
# decrypt stored secrets and backups (see: vpspilot backup).
DATABASE_USERNAME=vpspilot
DATABASE_PASSWORD=$(openssl rand -hex 24)
DATABASE_NAME=vpspilot
SECRET_KEY=$(openssl rand -hex 32)
ENCRYPTION_KEY=$(openssl rand -base64 32 | tr -d '=+/' | cut -c1-43)
FRONTEND_URL=https://$DOMAIN
CORS_ORIGINS=["https://$DOMAIN"]
COOKIE_SECURE=true
AGENT_API_URL=https://$DOMAIN
PUBLIC_API_URL=https://$DOMAIN
EMAIL_FROM=VPSPilot <onboarding@resend.dev>
RESEND_API_KEY=$RESEND_KEY
ENV
  umask 022
else
  say "Keeping the existing secrets in $ENV_FILE"
  sed -i "s#^FRONTEND_URL=.*#FRONTEND_URL=https://$DOMAIN#; s#^AGENT_API_URL=.*#AGENT_API_URL=https://$DOMAIN#; s#^PUBLIC_API_URL=.*#PUBLIC_API_URL=https://$DOMAIN#; s#^CORS_ORIGINS=.*#CORS_ORIGINS=[\"https://$DOMAIN\"]#" "$ENV_FILE"
  [ -n "$RESEND_KEY" ] && sed -i "s#^RESEND_API_KEY=.*#RESEND_API_KEY=$RESEND_KEY#" "$ENV_FILE"
fi
chmod 600 "$ENV_FILE"

docker network inspect vpspilot >/dev/null 2>&1 || docker network create vpspilot >/dev/null

say "Building and starting the control plane (a few minutes the first time)"
cd "$ROOT/api/deploy"
# --pull: re-running the installer also picks up base-image security fixes.
WEB_SOURCE="$ROOT/web" docker compose --env-file .env build --pull
WEB_SOURCE="$ROOT/web" docker compose --env-file .env up -d --remove-orphans

say "Waiting for the API"
for _ in $(seq 1 60); do
  if docker exec vpspilot-api python -c "import urllib.request; urllib.request.urlopen('http://127.0.0.1:8000/health')" >/dev/null 2>&1; then
    break
  fi
  sleep 2
done
docker exec vpspilot-api python -c "import urllib.request; urllib.request.urlopen('http://127.0.0.1:8000/health')" >/dev/null 2>&1 \
  || die "The API didn't come up. Check: docker logs vpspilot-api"

say "Configuring HTTPS for $DOMAIN"
mkdir -p "$PROXY_DIR/extra"
if [ "$TLS" = "internal" ]; then tls_line="tls internal"; else tls_line=""; fi
sed "s#__DOMAIN__#$DOMAIN#; s#__TLS__#$tls_line#" "$ROOT/api/deploy/control-plane.caddy.template" > "$PROXY_DIR/extra/control-plane.caddy"
if [ ! -f "$PROXY_DIR/Caddyfile" ]; then
  # Same layout the agent writes later, so the two never fight.
  {
    echo "# Managed by VPSPilot. Changes here are overwritten."
    echo "{"
    [ -n "$EMAIL" ] && echo "	email $EMAIL"
    echo "}"
    echo
    echo "import /etc/caddy/extra/*.caddy"
  } > "$PROXY_DIR/Caddyfile"
fi
chmod 644 "$PROXY_DIR/Caddyfile" "$PROXY_DIR/extra/control-plane.caddy"
if docker ps --format '{{.Names}}' | grep -qx vpspilot-proxy; then
  docker exec vpspilot-proxy caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null \
    && docker exec vpspilot-proxy caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null
else
  docker rm -f vpspilot-proxy >/dev/null 2>&1 || true
  docker run -d --name vpspilot-proxy --restart unless-stopped --network vpspilot \
    -p 80:80 -p 443:443 -p 443:443/udp \
    -v "$PROXY_DIR:/etc/caddy:ro" -v vpspilot-proxy-data:/data -v vpspilot-proxy-config:/config \
    --label vpspilot.proxy=1 --log-opt max-size=10m --log-opt max-file=3 \
    caddy:2-alpine caddy run --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null
fi

install -m 0755 "$ROOT/api/deploy/vpspilot" /usr/local/bin/vpspilot

ip=$(curl -fsS -4 --max-time 5 https://api.ipify.org 2>/dev/null || hostname -I | awk '{print $1}')
cat <<DONE

  VPSPilot is running.

  1. Point DNS for $DOMAIN to this server ($ip), if you haven't.
  2. Open https://$DOMAIN/setup and create the owner account.
  3. To manage this server too: Servers → Enroll Server, then run the
     command it shows here.

  Manage it with: vpspilot status | logs | upgrade | backup
  Secrets live in $ENV_FILE. Keep a copy somewhere safe (vpspilot backup).

DONE
